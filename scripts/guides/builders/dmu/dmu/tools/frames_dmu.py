def clip(b, x0):
    x, y, w, h = b
    x -= x0
    if x + w <= 0 or x >= CW or y >= CH:
        return None
    if x < 0:
        w += x
        x = 0
    return [x, y, min(w, CW - x), min(h, CH - y)]


def build(name):
    x0, extra, marks, lines, corner = F[name]
    blur = [c for c in (clip(b, x0) for b in FIXED + extra) if c]
    mk = []
    for m in marks:
        if m[0] == "ring":
            mk.append({"t": "ring", "at": [m[1] - x0, m[2]], "r": m[3]})
        else:
            mk.append({"t": "arrow", "from": [m[1][0] - x0, m[1][1]], "to": [m[2][0] - x0, m[2][1]]})
    at = {"tl": [12, 12], "bl": [12, CH - 2 * 37 - 32]}[corner]
    mk.append({"t": "label", "at": at, "lines": lines, "size": 28})
    spec = {"src": f"{W}/" + SRC.get(name, f"pk/{name}.png"), "out": f"{OUT}/{name}.webp", "crop": [x0, 0, CW, CH], "blur": blur, "marks": mk, "width": 1000}
    p = f"{SPECS}/{name}.json"
    json.dump(spec, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    r = subprocess.run(["node", "scripts/guides/annotate-frame.cjs", p], capture_output=True, text=True)
    print(name, (r.stdout.strip() or r.stderr.strip()[:300])[-70:])


for n in (sys.argv[1:] or list(F)):
    build(n)
