names = sys.argv[1:] or list(F)
for n in names:
    t, g, c, size, blur, marks = F[n]
    dx, dy = g[0] - c[0], g[1] - c[1]
    mv = lambda p: [p[0] + dx, p[1] + dy]
    bl = []
    for b in blur:  # moved, then clipped to the crop (a box past the edge is dropped)
        x0, y0 = max(0, b[0] + dx), max(0, b[1] + dy)
        x1, y1 = min(size[0], b[0] + dx + b[2]), min(size[1], b[1] + dy + b[3])
        if x1 - x0 >= 8 and y1 - y0 >= 8:
            bl.append([x0, y0, x1 - x0, y1 - y0])
    mk = []
    for m in marks:
        m = dict(m)
        if m["t"] == "ring":
            m["at"] = mv(m["at"])
        elif m["t"] == "arrow":
            m["from"], m["to"] = mv(m["from"]), mv(m["to"])
        mk.append(m)
    spec = {"src": f"{M9}/fr/f-{t}.png", "out": f"{OUT}/{n}.webp", "crop": [c[0], c[1], size[0], size[1]],
            "blur": bl, "marks": mk, "width": 1000}
    p = f"{M9}/specs/{n}.json"
    json.dump(spec, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    r = subprocess.run(["node", "scripts/guides/annotate-frame.cjs", p], cwd=WT, capture_output=True, text=True)
    print(n, (r.stdout.strip() or r.stderr.strip()[:300]))
