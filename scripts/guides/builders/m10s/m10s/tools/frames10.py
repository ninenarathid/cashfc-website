def url(name):
    return f"https://youtu.be/{VID}?t={int(F[name][0])}"


def build(name):
    t, x0, y0, blur, marks, label = F[name]
    mk = list(marks) + [{"t": "label", "at": [18, 18], "lines": label, "size": 30}]
    spec = {"src": f"{M}/fr/f-{t}.png", "out": f"{OUT}/{name}.webp", "crop": [x0, y0, CW, CH], "blur": blur, "marks": mk, "width": 1000}
    p = f"{M}/specs/{name}.json"
    json.dump(spec, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    r = subprocess.run(["node", "scripts/guides/annotate-frame.cjs", p], cwd=WT, capture_output=True, text=True)
    print(name, (r.stdout.strip() or r.stderr.strip())[-90:])


if __name__ == "__main__":
    for name in sys.argv[1:] or list(F):
        build(name)
