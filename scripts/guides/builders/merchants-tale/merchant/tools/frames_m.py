    blur = []
    for b in HUD[src[:2]] + extra:
        bx = box(b, crop)
        if bx[0] + bx[2] <= 0 or bx[1] + bx[3] <= 0 or bx[0] >= crop[2] or bx[1] >= crop[3]:
            continue
        bx = [max(0, bx[0]), max(0, bx[1]), bx[2] + min(0, bx[0]), bx[3] + min(0, bx[1])]
        blur.append(bx)
