-- v172 — a tree is felled at its board
--
-- Run this once in the Supabase SQL editor, after v164 (it stops at its first line without v164's rule of felling).
-- Running it again is safe. The site's code that goes with it is live first: the page no longer has the press this
-- takes away. A page left open from before still shows that press, and from this file on it does nothing.
--
-- Why. The owner, 2026-10-09, three hours after the mountain opened to everybody:
--
--   "เอาระบบตัดไม้เร็วออก ต้องเล่น มินิเกมทุกครั้ง มีคนตัดเร็วๆจนคนอื่นไม่ได้ตัด"
--
-- Beside a tree there were two presses: the board, and a plain one that felled the tree at once for its logs with no
-- board at all. Whoever only pressed the plain one walked the mountain taking every tree, and nobody else had one.
--
-- What it does: `town.fell` (v164's) written again, as it stood but for one condition: a go that asks for the plain
-- way is refused (`board`), after every refusal there was before it. A tree is felled at its board, or by an axe's
-- own counted chop, as before; a go that is lost on the board still fells its tree for its logs, as before. No
-- table, no column, no catalog row, no coins; nobody's purse and no tree is touched. Who may call what is as it was
-- (a function written again keeps its grants; the schema's line is said again all the same).

